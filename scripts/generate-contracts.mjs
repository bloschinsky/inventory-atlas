import { createClient } from '@hey-api/openapi-ts';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { generateOpenApi, openApiPath } from './generate-openapi.mjs';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const prettierOptions = (await resolveConfig(path.join(repositoryRoot, 'package.json'))) ?? {};
export const generatedRoot = path.join(repositoryRoot, 'packages', 'contracts', 'src', 'generated');

async function generatedFiles(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await generatedFiles(target)));
    else files.push(target);
  }
  return files;
}

function declarationNames(document) {
  return Object.keys(document.components?.schemas ?? {}).sort((left, right) =>
    left.localeCompare(right),
  );
}

async function writeJavaScriptDeclarations(document, checksum) {
  const names = declarationNames(document);
  const jsdoc = [
    `// OpenAPI-SHA256: ${checksum}`,
    '// Generated by scripts/generate-contracts.mjs. Do not edit.',
    ...names.flatMap((name) => [
      '/**',
      ` * @typedef {import('./types.gen.js').${name}} ${name}`,
      ' */',
    ]),
    'export {};',
    '',
  ].join('\n');
  const declarations = [
    `// OpenAPI-SHA256: ${checksum}`,
    '// Generated by scripts/generate-contracts.mjs. Do not edit.',
    `export type { ${names.join(', ')} } from './types.gen.js';`,
    '',
  ].join('\n');
  await Promise.all([
    writeFile(path.join(generatedRoot, 'jsdoc.gen.js'), jsdoc, 'utf8'),
    writeFile(path.join(generatedRoot, 'contracts.gen.d.ts'), declarations, 'utf8'),
  ]);
}

async function stampGeneratedFiles(checksum) {
  const marker = `// OpenAPI-SHA256: ${checksum}`;
  for (const file of await generatedFiles(generatedRoot)) {
    const source = await readFile(file, 'utf8');
    const stamped = source.startsWith(marker) ? source : `${marker}\n${source}`;
    await writeFile(file, await format(stamped, { ...prettierOptions, filepath: file }), 'utf8');
  }
}

export async function generateContracts() {
  await mkdir(generatedRoot, { recursive: true });
  const { checksum, document } = await generateOpenApi();
  await createClient({
    input: openApiPath,
    output: { clean: true, path: generatedRoot },
    plugins: ['@hey-api/client-fetch', '@hey-api/typescript', '@hey-api/sdk', 'zod'],
  });
  await writeJavaScriptDeclarations(document, checksum);
  await stampGeneratedFiles(checksum);
  return checksum;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const checksum = await generateContracts();
  process.stdout.write(`contracts:generate: wrote OpenAPI and client artifacts (${checksum}).\n`);
}
